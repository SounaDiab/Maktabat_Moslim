                      'وفي (البلد الامين) عن رسول الله (صلّى الله عليه وآله وسلم) قال: من قال كل يوم عشر مرات: بِسْمِ الله الرَّحْمنِ الرَّحيمِ لا حَوْلَ وَلا قوَةَ إِلاّ بِالله العَلي العَظيمِ خرج من ذنوبه كيوم ولدته أمّه ودفع الله عنه سبعين بابا من البلاء منها الجنون والجذام والبرص والفالج ووكّل الله تعالى به سبعين ألف ملك يستغفرون له. وعن الصادق (عليه السلام) قال: من قال كل يوم مائة مرة : لا حَولَ وَلا قوةَ إِلاّ بِالله لم يصبه الفقر.\n\n'
