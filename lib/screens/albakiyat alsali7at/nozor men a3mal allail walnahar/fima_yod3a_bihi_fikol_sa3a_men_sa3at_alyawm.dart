                      'وروي في (البلد الامين) عن النبي (صلّى الله عليه وآله وسلم): أن من قال هذه الكلمات في كل يوم عشراً غفر الله تعالى له أربعة اَّلاف كبيرة ووقاه من شر سكرات الموت وضغطة القبر ومائة هول من أهوال يوم القيامة ووقي من شر إبليس وجنوده وقضي دينه وكشف همّه وغمّه وفرّج كربه وهي هذه: أعْدَدْتُ لِكُلِّ هَولٍ لا إلهَ إِلاّ الله وَلِكُلِّ هَمٍّ وَغَمٍّ ماشاء الله وَلِكُلِّ نِعْمَةٍ الحَمْدُ لله وَلِكُلِّ رَخاءٍ الشُّكْرُ لله وَلِكُلِّ أُعْجوبَةٍ سَبْحانَ الله وَلِكُلِّ ذَنْبٍ أسْتَغْفِرُ الله وَلِكُلِّ مُصيبَةٍ إنّا لله وَإنّا إلَيهِ راجِعونَ وَلِكُلِّ ضيقٍ حَسْبي الله وَلِكُلِّ قَضاء وَقَدَرٍ تَوَكَّلْتُ عَلى الله وَلِكُلِّ عَدوٍّ إعْتَصَمْتُ بِالله وَلِكُلِّ طاعَةٍ وَمَعْصيةٍ لا حَولَ وَلا قوةَ إِلاّ بِالله العَليّ العَظيم.\n\n'
