                      'وَاَمْرُكَ حِلْمٌ وَعَزْمٌ، وَرَأيُكَ عِلْمٌ وَحَزْمٌ، اعْتَدَلَ بِكَ الدّينُ، وَسَهُلَ بِكَ الْعَسيرُ، وَاُطْفِئَتْ بِكَ النّيرانُ، وَقَوِيَ بِكَ الاْيمانُ، وَثَبَتَ بِكَ الاِْسْلامُ، وَهَدَّتْ مُصيبَتُكَ الاَْنامَ، فَاِنّا للهِ وَاِنّا اِلَيْهِ راجِعوُنَ، لَعَنَ اللهُ مَنْ قَتَلَكَ، وَلَعَنَ اللهُ مَنْ خالَفَكَ، وَلَعَنَ اللهُ مَنِ افْتَرى عَلَيْكَ، وَلَعَنَ اللهُ مَنْ ظَلَمَكَ وَغَصَبَكَ حَقَّكَ، وَلَعَنَ اللهُ مَنْ بَلَغَهُ ذلِكَ فَرَضِيَ بِهِ، اِنّا اِلَى اللهِ مِنْهُمْ بُرَاءُ، لَعَنَ اللهُ اُمَّةً خالَفَتْكَ، وَجَحَدَتْ وِلايَتَكَ، وَتَظاهَرَتْ عَلَيْكَ، وَقَتَلَتْكَ وَحادَتْ عَنْكَ وَخَذَلَتْكَ، اَلْحَمْدُ للهِ الَّذي جَعَلَ النّارَ مَثْواهُمْ، وَبِئْسَ الْوِرْدُ الْمَوْرُودُ، اَشْهَدُ لَكَ يا وَلِيَّ اللهِ وَوَلِيَّ رَسُولِهِ صَلَّى اللهُ عَلَيْهِ وَآلِهِ بِالْبَلاغِ وَالاَْداءِ، وَاَشْهَدُ اَنَّكَ حَبيبُ اللهِ وَبابُهُ، وَاَنَّكَ جَنْبُ اللهِ وَوَجْهُهُ الَّذي مِنْهُ يُؤْتى، وَاَنَّكَ سَبيلُ اللهِ، وَاَنَّكَ عَبْدُ اللهِ وَاخُو رَسُولِهِ صَلَّى اللهُ عَلَيْهِ وَآلِهِ، اَتَيْتُكَ زائِراً لِعَظيمِ حالِكَ وَمَنْزِلَتِكَ عِنْدَ اللهِ وَعِنْدَ رَسُولِهِ، مُتَقَرِّباً اِلَى اللهِ بِزِيارَتِكَ، راغِباً اِلَيْكَ فِي الشَّفاعَةِ، '
                      'ابْتَغي بِشَفاعَتِكَ خَلاصَ نَفْسي، مُتَعَوِّذاً بِكَ مِنَ النّارِ، هارِباً مِنْ ذُنوُبِي الَّتِي احْتَطَبْتُها عَلى ظَهْري، فَزِعاً اِلَيْكَ رَجآءَ رَحْمَةِ رَبّي، اَتَيْتُكَ اَسْتَشْفِعُ بِكَ يا مَوْلاىَ اِلَى اللهِ وَاَتَقَرَّبُ بِكَ اِلَيْهِ لِيَقْضِيَ بِكَ حَوائِجي، فَاشْفَعْ لي يا اَميرَ الْمُؤْمِنينَ اِلَى اللهِ فَاِنّي عَبْدُ اللهِ وَمَوْلاكَ وَزائِرُكَ، وَلَكَ عِنْدَ اللهِ الْمَقامُ الْمَعْلُومُ وَالْجاهُ الْعَظيمُ، وَالشَّأنُ الْكَبيرُ، وَالشَّفاعَةُ الْمَقْبُولَةُ، اَللّـهُمَّ صَلِّ عَلى مُحَمَّد وَآلِ مُحَمَّد، وَصَلِّ عَلى عَبْدِكَ وَاَمينِكَ الاَْوْفى، وَعُرْوَتِكَ الْوُثْقى، وَيَدِكَ الْعُلْيا، وَكَلِمَتُكَ الْحُسْنى، وَحُجَّتِكَ عَلَى الْوَرى، وَصِدِّيْقِكَ الاَْكْبَرِ سَيّدِ الاَْوْصِياءِ، وَرُكْنِ الاَْوْلِياءِ، وَعِمادِ الاَْصْفِياءِ، اَميرِ الْمُؤْمِنينَ، وَيَعْسُوبِ الْمُتَّقينَ، وَقُدْوَةِ الصِّدّيقينَ، وَاِمامِ الصّالِحينَ، الْمَعْصُومِ مِنَ الزَّلَلِ، وَالْمَفْطُومِ مِنَ الْخَلَلِ، وَالْمُهَذَّبِ مِنَ الْعَيْبِ، وَالْمُطَهَّرِ مِنَ الرَّيْبِ، اَخي نَبِيِّكَ وَوَصِيِّ رَسُولِكَ، وَالْبائِتِ عَلى فِراشِهِ، وَالْمُواسي لَهُ بِنَفْسِهِ، وَكاشِفِ الْكَرْبِ عَنْ وَجْهِهِ، الَّذي جَعَلْتَهُ سَيْفاً لِنُبُوَّتِهِ، وَمُعْجِزاً لِرِسالَتِهِ، وَدِلالَةً واضِحَةً لِحُجَّتِهِ، وَحامِلاً لِرايَتِهِ، وَوِقايَةً لِمُهْجَتِهِ، وَهادِياً لاُِمَّتِهِ، '
                      'وَيَداً لِبَأسِهِ، وَتاجاً لِرَأسِهِ، وَباباً لِنَصْرِهِ، وَمِفْتاحاً لِظَفَرِهِ، حَتّى هَزَمَ جُنُودَ الشِّرْكِ بِاَيْدِكَ، وَاَبادَ عَساكِرَ الْكُفْرِ بِاَمْرِكَ، وَبَذَلَ نَفْسَهُ في مَرْضاتِكَ وَمَرْضاةِ رَسُولِكَ، وَجَعَلَها وَقْفاً عَلى طاعَتِهِ، وَمَجِنّاً دُونَ نَكْبَتِهِ، حَتّى فاضَتْ نَفْسُهُ صَلَّى اللهُ عَلَيْهِ وَآلِهِ في كَفِّهِ، وَاسْتَلَبَ بَرْدَها وَمَسَحَهُ عَلى وَجْهِهِ، وَاَعانَتْهُ مَلائِكتُكَ على غُسْلِهِ وَتَجْهيزِهِ، وَصَلّى عَلَيْهِ وَوارى شَخْصَهُ، '
                      'وَقَضى دَيْنَهُ، وَاَنْجَزَ وَعْدَهُ، وَلَزِمَ عَهْدَهُ، وَاحْتَذى مِثالَهُ، وَحَفِظَ وَصِيَّتَهُ، وَحينَ وَجَدَ اَنْصاراً نَهَضَ مُسْتَقِلاًّ بِاَعْباءِ الْخِلافَةِ مُضْطَلِعاً بِاَثْقالِ الاْمامَةِ، فَنَصَبَ رايَةَ الْهُدى في عِبادِكَ، وَنَشَرَ ثَوْبَ الاَْمْنِ في بِلادِكَ، وَبَسَطَ الْعَدْلَ في بَرِيَّتِكَ، وَحَكَمَ بِكِتابِكَ في خَليقَتِكَ، وَاَقامَ الْحُدُودَ، وَقَمَعَ الْجُحُودَ، وَقَوَّمَ الزَّيْغَ، وَسَكَّنَ الْغَمْرَةَ، وَاَبادَ الْفَتْرَةَ، وَسَدَّ الْفُرْجَةَ، وَقَتَلَ النّاكِثَةَ وَالْقاسِطَةَ وَالْمارِقَةَ، وَلَمْ يَزَلْ عَلى مِنْهاجِ رَسُولِ اللهِ صَلَّى اللهُ عَلَيْهِ وَآلِهِ وَوَتيرَتِهِ،وَلُطْفِ شاكِلَتِهِ، وَجَمالِ سيرَتِهِ، مُقْتَدِياً بِسُنَّتِهِ، مُتَعَلِّقاً بِهِمَّتِهِ، مُباشِراً لِطَريقَتِهِ، وَاَمْثِلَتُهُ نَصبُ عَيْنَيْهِ، يَحْمِلُ عِبادَكَ عَلَيْها وَيَدْعُوهُمْ اِلَيْها، اِلى اَنْ خُضِبَتْ شَيْبَتُهُ مِنْ دَمِ رَأسِهِ، اَللّـهُمَّ فَكَما لَمْ يُؤْثِرْ في طاعَتِكَ شَكّاً عَلى يَقين، وَلَمْ يُشْرِكْ بِكَ طَرْفَةَ عَيْن، صَلِّ عَلَيْهِ صَلاةً زاكِيَةً نامِيَةً يَلْحَقُ بِها دَرَجَةَ النُّبُوَّةِ في جَنَّتِكَ، وَبَلِّغْهُ مِنّا تَحِيَّةً وَسَلاماً، وَآتِنا مِنْ لَدُنْكَ في مُوالاتِهِ فَضْلاً وَاِحْساناً وَمَغْفِرَةً وَرِضْواناً، اِنَّكَ ذُو الْفَضْلِ الْجَسيمِ بِرَحْمَتِكَ يا اَرْحَمَ الرّاحِمينَ.\n\n'
