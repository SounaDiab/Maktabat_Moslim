class DouaaZamanAlghaiba extends StatefulWidget {
  static String screenRoute = 'douaa_zaman_alghaiba_screen';
  const DouaaZamanAlghaiba({super.key});

  @override
  State<DouaaZamanAlghaiba> createState() => _DouaaZamanAlghaibaState();
}

double _fontSize = 18;
double _fontSizeTablet = 30;

class _DouaaZamanAlghaibaState extends State<DouaaZamanAlghaiba> {
  bool isIcon = true;
  @override
  void initState() {
    super.initState();
    _loadFavoriteState();
  }

  Future<void> _loadFavoriteState() async {
    final prefs = await SharedPreferences.getInstance();
    bool? savedState = prefs.getBool('isFavorite_douaa_zaman_alghaiba_screen');
    setState(() {
      isIcon = savedState ?? true;
    });
  }

  Future<void> _saveFavoriteState(bool value) async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.setBool('isFavorite_douaa_zaman_alghaiba_screen', value);
  }

  Future<bool> _onWillPop() async {
    final args =
        ModalRoute.of(context)!.settings.arguments as Map<String, dynamic>?;
    final previousPage = args?['previousPage'];
    if (previousPage == 'favorite_screen') {
      Navigator.of(context).pushReplacementNamed(FavoritesScreen.screenRoute);
      return false;
    } else {
      Navigator.of(context)
          .pushReplacementNamed(Ad3iyaMashhoura.screenRoute);
      return false;
    }
  }

