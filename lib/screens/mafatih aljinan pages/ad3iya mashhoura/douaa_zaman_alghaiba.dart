                  Provider.of<FavoritesProvider>(context, listen: false)
                      .removeFavorite(
                          'دعاء زمن الغيبة',
                          DouaaZamanAlghaiba.screenRoute,
                          DouaaZamanAlghaiba.screenRoute);
                }
              },
            ),
          ],
          title: Text(
            'دعاء زمن الغيبة',
            style: TextStyle(
              fontSize: isTablet
                  ? 40
                  : size > 1.0
                      ? 20
                      : 23,
              fontWeight: FontWeight.bold,
            ),
          ),
        ),
        body: ContainerScrollview(
          widget: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Container(
                child: Column(
                  children: [
                    Center(
                      child: Text(
                        'بسم الله الرحمن الرحيم',
